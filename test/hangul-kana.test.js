import { test } from 'node:test';
import assert from 'node:assert/strict';
import { hangulToKatakana } from '../src/hangul-kana.js';

const eq = (input, expected) => assert.equal(hangulToKatakana(input), expected);

test('hangulToKatakana: 빈 입력', () => {
  eq('', '');
  eq(null, '');
  eq(undefined, '');
});

test('hangulToKatakana: 기본 음절 (초성+중성)', () => {
  eq('가', 'カ');
  eq('나', 'ナ');
  eq('아', 'ア');
  eq('하', 'ハ');
  eq('시', 'シ');
  eq('스', 'ス');
});

test('hangulToKatakana: ㅓ/ㅗ, ㅡ/ㅜ, ㅐ/ㅔ는 일본어에 대립이 없어 하나로 합쳐진다', () => {
  eq('서', 'ソ');
  eq('소', 'ソ');
  eq('그', 'ク');
  eq('구', 'ク');
  eq('개', 'ケ');
  eq('게', 'ケ');
});

test('hangulToKatakana: 요음 (ㅑㅕㅛㅠ)', () => {
  eq('갸', 'キャ');
  eq('겨', 'キョ');
  eq('뇨', 'ニョ');
  eq('휴', 'ヒュ');
  eq('야', 'ヤ');
});

test('hangulToKatakana: 합요음 — ㄱ·ㅎ·ㅇ은 전용 가나, 나머지는 u단+모음으로 근사', () => {
  eq('과', 'クァ');
  eq('화', 'ファ');
  eq('회', 'フェ');
  eq('와', 'ワ');
  eq('위', 'ウィ');
  eq('뭐', 'ムオ');   // ムォ는 표준 가나가 아니라 통상 크기 모음으로 근사한다
});

test('hangulToKatakana: 종성은 7종성으로 중화된다', () => {
  eq('악', 'アク');
  eq('안', 'アン');
  eq('알', 'アル');
  eq('암', 'アム');
  eq('압', 'アプ');
  eq('앙', 'アン');   // ㄴ받침과 구분되지 않는다 — 일본어에 표기가 없다
  eq('앋', 'アッ');
});

test('hangulToKatakana: 겹받침도 대표음으로 중화된다', () => {
  eq('삯', 'サク');   // ㄳ → ㄱ
  eq('닭', 'タク');   // ㄺ → ㄱ
  eq('삶', 'サム');   // ㄻ → ㅁ
  eq('값', 'カプ');   // ㅄ → ㅂ
});

test('hangulToKatakana: 연음 — 받침이 뒤따르는 초성 ㅇ 자리로 넘어간다', () => {
  eq('한국어', 'ハングゴ');   // 한구거. 연음이 없으면 ハンクオ가 되어 알아들을 수 없다
  eq('있어요', 'イッソヨ');   // 이써요
  eq('읽어요', 'イルゴヨ');   // 일거요 — 겹받침은 하나만 넘어간다
  eq('앉아', 'アンジャ');     // 안자
  eq('밟아', 'パルバ');       // 발바
  eq('옷이', 'オシ');         // 오시
});

test('hangulToKatakana: 연음 — ㅎ은 넘어가지 않고 탈락한다', () => {
  eq('좋아요', 'チョアヨ');    // 조아요
  eq('많아', 'マナ');          // 마나 — ㄶ은 ㅎ만 빠지고 ㄴ이 넘어간다
  eq('싫어', 'シロ');          // 시러
  eq('괜찮아', 'クェンチャナ'); // 괜차나
});

test('hangulToKatakana: 연음은 공백·문장부호를 넘지 않는다', () => {
  eq('밥 안', 'パプ アン');
  eq('밥,안', 'パプ,アン');
});

test('hangulToKatakana: 평음은 모음·유성 받침 뒤에서 유성음화한다', () => {
  eq('부산', 'プサン');       // 어두 ㅂ은 무성
  eq('대박', 'テバク');       // 모음 뒤 ㅂ → バ
  eq('불고기', 'プルゴギ');   // ㄹ 뒤 ㄱ → ゴ, 모음 뒤 ㄱ → ギ
  eq('아버지', 'アボジ');     // 모음 뒤 ㅈ → ジ
});

test('hangulToKatakana: 거센소리·된소리는 유성음화하지 않는다', () => {
  eq('가치', 'カチ');     // ㅊ은 유성 변이형이 없다
  eq('가카', 'カカ');     // ㅋ도 마찬가지
  eq('아빠', 'アッパ');
});

test('hangulToKatakana: 된소리의 촉음은 앞이 받침 없이 끝날 때만 붙는다', () => {
  eq('짜장면', 'チャジャンミョン'); // 어두에는 촉음을 붙이지 않는다 (일본어는 ッ로 시작 못 한다)
  eq('오빠', 'オッパ');             // 모음 뒤에는 붙는다
  eq('넋이', 'ノクシ');             // 앞에 이미 받침이 있으면 겹쳐 읽히므로 생략
  eq('값이', 'カプシ');
});

test('hangulToKatakana: 비음화 — 파열 받침이 ㄴ·ㅁ 앞에서 비음이 된다', () => {
  eq('감사합니다', 'カムサハムニダ'); // 감사함니다 — 존댓말 어미라 제일 자주 걸린다
  eq('있습니다', 'イッスムニダ');
  eq('대박입니다', 'テバギムニダ');
  eq('한국말', 'ハングンマル');       // 한궁말
  eq('밥먹자', 'パムモクチャ');       // 밤먹자
  eq('앞머리', 'アムモリ');           // 암머리
});

test('hangulToKatakana: 비음화는 뒤 음절이 ㄴ·ㅁ으로 시작할 때만 일어난다', () => {
  eq('악기', 'アクキ');
  eq('밥그릇', 'パプクルッ');
  eq('밥 먹자', 'パプ モクチャ'); // 공백 너머로는 건너가지 않는다
});

test('hangulToKatakana: 유음화 — ㄴ과 ㄹ이 만나면 둘 다 ㄹ이 된다', () => {
  eq('신라', 'シルラ');   // 실라
  eq('연락', 'ヨルラク'); // 열락
  eq('설날', 'ソルラル'); // 설랄
});

test('hangulToKatakana: 받침 ㅇ은 유음화하지 않는다', () => {
  eq('종로', 'チョンロ'); // ㄹ비음화(종노)는 구현 범위 밖 — 적어도 졸로가 되지는 않는다
});

test('hangulToKatakana: 한글이 아닌 문자는 그대로 통과한다', () => {
  eq('Deadly Trick 재밌다', 'Deadly Trick チェミッタ');
  eq('123', '123');
  eq('ずんだもん', 'ずんだもん');
  eq('!?~', '!?~');
});

test('hangulToKatakana: 한글과 다른 문자가 섞여도 음절 단위로만 변환한다', () => {
  eq('안녕 zundamon!', 'アンニョン zundamon!');
});
